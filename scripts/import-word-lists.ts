// Builds the race word lists from the OpenSubtitles 2018 frequency lists of FrequencyWords (Hermit Dave, content under CC BY-SA 4.0).
// Keeps the most frequent words of 2 to 10 letters, letters only, minus scripts/data/word-blocklist.ts.
// Regenerate with: npx tsx scripts/import-word-lists.ts
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { wordBlocklist } from './data/word-blocklist';
import { raceWordPatterns, type TextLanguage } from '../src/domain/text-settings';

const wordsPerLanguage = 1000;
const wordsPerLine = 12;

const sourceUrl = (language: TextLanguage) => `https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/${language}/${language}_50k.txt`;

const exportNames: Record<TextLanguage, string> = { fr: 'frenchWords', en: 'englishWords' };

async function importLanguage(language: TextLanguage): Promise<void> {
  const response = await fetch(sourceUrl(language));
  if (!response.ok) throw new Error(`Download failed for ${language}: ${response.status}`);
  const words = keptWords(await response.text(), language);
  if (words.length < wordsPerLanguage) throw new Error(`Only ${words.length} ${language} words passed the filters.`);
  writeFileSync(resolve(process.cwd(), `src/assets/word-lists/${language}.ts`), moduleSource(language, words));
}

function keptWords(frequencyList: string, language: TextLanguage): string[] {
  const blocked = new Set<string>(wordBlocklist[language]);
  const ranked = frequencyList.split('\n').map((line) => line.split(' ')[0]!.normalize('NFC'));
  const kept = ranked.filter((word) => raceWordPatterns[language].test(word) && !blocked.has(word));
  return [...new Set(kept)].slice(0, wordsPerLanguage);
}

function moduleSource(language: TextLanguage, words: readonly string[]): string {
  return [
    `// Generated by scripts/import-word-lists.ts from ${sourceUrl(language)}`,
    '// FrequencyWords by Hermit Dave, from OpenSubtitles 2018, content under CC BY-SA 4.0; this filtered list is shared under the same license.',
    `export const ${exportNames[language]}: readonly string[] = [`,
    ...linesOf(words),
    '];',
    '',
  ].join('\n');
}

function linesOf(words: readonly string[]): string[] {
  const lines: string[] = [];
  for (let start = 0; start < words.length; start += wordsPerLine) lines.push(`  ${words.slice(start, start + wordsPerLine).map((word) => `'${word}'`).join(', ')},`);
  return lines;
}

async function run(): Promise<void> {
  await importLanguage('fr');
  await importLanguage('en');
}

run().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
