"""Import the evolutions caused by an evolution stone or an evolution item for Pokédex #1-649, from PokeAPI evolution data (Generations I-V).
A held or traded item is used from the collection like a stone; Magnezone and Probopass use the Thunder Stone.
Regenerate with: python3 scripts/import-item-evolutions.py
"""
import json
from catalog import root
from evolution_source import csv_source, evolution_rules

evolutions = sorted(
    ({'from': pair[0], 'into': pair[1], 'item': rule[1]} for pair, rule in evolution_rules().items() if rule[0] == 'item'),
    key=lambda evolution: evolution['into'],
)
pairs = {(evolution['from'], evolution['item']) for evolution in evolutions}
assert len(pairs) == len(evolutions), 'one item evolves a species into two forms'

lines = ',\n'.join('  ' + json.dumps(evolution, separators=(', ', ': ')) for evolution in evolutions)
header = f'// Generated by scripts/import-item-evolutions.py from {csv_source}pokemon_evolution.csv and items.csv (Generations I-V).\n'
(root / 'src/assets/item-evolutions.ts').write_text(
    header + 'export const itemEvolutions = [\n' + lines + '\n] as const;\n\nexport type ItemEvolution = (typeof itemEvolutions)[number];\n'
)
print(f'{len(evolutions)} item evolutions written.')
