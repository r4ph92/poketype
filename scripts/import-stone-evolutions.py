"""Import the Kanto evolutions triggered by an evolution stone in the original games, from PokeAPI evolution data.
Only the five stones of the shop are kept. Regenerate with: python3 scripts/import-stone-evolutions.py
"""
from pathlib import Path
from urllib.request import urlopen
import csv
import io
import json

evolution_source = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_evolution.csv'
item_source = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/items.csv'
use_item_trigger = '3'
original_version_group = '1'
shop_stones = {'fire-stone', 'water-stone', 'thunder-stone', 'leaf-stone', 'moon-stone'}

root = Path(__file__).resolve().parent.parent
catalog = json.loads((root / 'scripts/data/kanto.json').read_text())
evolves_from = {entry['dex']: entry['evolvesFrom'] for entry in catalog}


def read_csv(url):
    with urlopen(url, timeout=30) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode('utf-8'))))


item_names = {row['id']: row['identifier'] for row in read_csv(item_source)}

# Version group 1 (Red/Blue) holds the original rule; later version groups add regional forms.
evolutions = sorted(
    (
        {'from': evolves_from[into], 'into': into, 'stone': item_names[row['trigger_item_id']]}
        for row in read_csv(evolution_source)
        if (into := int(row['evolved_species_id'])) in evolves_from
        and evolves_from[into] is not None
        and row['version_group_id'] == original_version_group
        and row['evolution_trigger_id'] == use_item_trigger
        and item_names.get(row['trigger_item_id']) in shop_stones
    ),
    key=lambda evolution: evolution['into'],
)
pairs = {(evolution['from'], evolution['stone']) for evolution in evolutions}
assert len(pairs) == len(evolutions), 'one stone evolves a species into two forms'

header = f'// Generated by scripts/import-stone-evolutions.py from {evolution_source} and {item_source} (original-game rules only).\n'
(root / 'src/assets/stone-evolutions.ts').write_text(
    header + 'export const stoneEvolutions = ' + json.dumps(evolutions, indent=2) + ' as const;\n\nexport type StoneEvolution = (typeof stoneEvolutions)[number];\n'
)
print(f'{len(evolutions)} stone evolutions written.')
