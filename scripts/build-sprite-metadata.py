"""Read unmodified local PMDCollab sheets/XML. No network or image manipulation.
Regenerate the typed sheet manifest and CSS with: python3 scripts/build-sprite-metadata.py
"""
from pathlib import Path
import json
import struct
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parent.parent
catalog = json.loads((root / 'scripts/data/kanto.json').read_text())
species = {entry['species']: entry['dex'] for entry in catalog}
credit_names = {parts[1]: parts[0] for line in (root / 'scripts/data/sprite-credit-names.txt').read_text().splitlines()[1:] if len(parts := line.split('\t')) >= 2}
manifest = {}
css = ['/* Generated from PMDCollab AnimData.xml; frame durations are 1/60 second. */']
for name, dex in species.items():
    folder = root / 'public/assets/sprites/pokemon' / name
    animations = ET.parse(folder / 'AnimData.xml').getroot().find('Anims')
    manifest[name] = {'dex': dex, 'source': f'https://github.com/PMDCollab/SpriteCollab/tree/master/sprite/{dex:04d}', 'credit': 'CHUNSOFT', 'terms': 'Official game artwork (upstream credits: Unspecified); not relicensed under the community contribution license.', 'retrieved': '2026-10-01', 'modification': 'None; original animation sheets and XML retained.', 'creditsPath': f'/assets/sprites/pokemon/{name}/credits.txt'}
    for state in ['Walk', 'Idle']:
        animation = next(a for a in animations if a.findtext('Name') == state)
        while animation.findtext('CopyOf'):
            animation = next(a for a in animations if a.findtext('Name') == animation.findtext('CopyOf'))
        source_state = animation.findtext('Name')
        width, height = int(animation.findtext('FrameWidth')), int(animation.findtext('FrameHeight'))
        durations = [int(d.text) for d in animation.find('Durations')]
        raw = (folder / f'{source_state}-Anim.png').read_bytes()
        sheet_width, sheet_height = struct.unpack('>II', raw[16:24])
        assert sheet_width == width * len(durations)
        assert sheet_height == height * 8
        # Record attribution for the imported actions, not unrelated community-authored attacks.
        credits = (folder / 'credits.txt').read_text().splitlines()
        applicable = [c.split('\t')[1] for c in credits if source_state in c.split('\t')[-1].split(',')]
        assert applicable, (name, state, 'missing action credit')
        authors = sorted(set(manifest[name].get('authors', []) + applicable))
        manifest[name]['authors'] = authors
        manifest[name]['credit'] = ', '.join(credit_names.get(author, author) for author in authors)
        manifest[name]['terms'] = 'See original credits.txt for per-action attribution and license terms; official artwork is not relicensed.'
        action = state.lower()
        manifest[name][action] = {'src': f'/assets/sprites/pokemon/{name}/{source_state}-Anim.png', 'width': width, 'height': height, 'sheetWidth': sheet_width, 'sheetHeight': sheet_height, 'durations': durations}
        total, elapsed = sum(durations), 0
        css.append(f'@keyframes sprite-{name}-{action} {{')
        for index, duration in enumerate(durations):
            css.append(f'  {elapsed / total * 100:.6f}% {{ transform: translateX(calc(var(--sprite-frame-width) * -{index})); }}')
            elapsed += duration
        css.append('  100% { transform: translateX(0); }\n}')
(root / 'src/assets/pokemon.ts').write_text('// Generated by scripts/build-sprite-metadata.py from local source metadata.\nexport const pokemonArtwork = ' + json.dumps(manifest, indent=2) + ' as const;\n\nexport type PokemonSpecies = keyof typeof pokemonArtwork;\n')
(root / 'src/assets/sprite-animations.css').write_text('\n'.join(css) + '\n')

entries = [{k: v for k, v in entry.items() if k != 'names'} for entry in catalog]
(root / 'src/assets/pokedex.ts').write_text('// Catalog source: PokeAPI species CSV; localized names are in messages.\nexport const pokedex = ' + json.dumps(entries, indent=2) + ' as const;\nexport type PokedexEntry = (typeof pokedex)[number];\nexport type PokedexDex = PokedexEntry["dex"];\n')
for locale in ['en', 'fr']:
    path = root / f'messages/{locale}.json'
    messages = json.loads(path.read_text())
    for entry in catalog:
        messages['Pokemon'][entry['species']] = entry['names'][locale]
        messages['Trainer']['species'][str(entry['dex'])] = entry['names'][locale]
    path.write_text(json.dumps(messages, indent=2, ensure_ascii=False) + '\n')
