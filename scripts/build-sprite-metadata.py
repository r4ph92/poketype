"""Read unmodified local PMDCollab sheets/XML and front artwork. No network or image manipulation.
Writes the Pokédex catalog, the compact sprite sheets the client needs, the per-species credits (read on the server) and the species names.
Regenerate with: python3 scripts/build-sprite-metadata.py
"""
import json
import struct
import xml.etree.ElementTree as ET
from catalog import load_catalog, regions, root

catalog = load_catalog()
credit_names = {parts[1]: parts[0] for line in (root / 'scripts/data/sprite-credit-names.txt').read_text().splitlines()[1:] if len(parts := line.split('\t')) >= 2}
retrieved = {'kanto': '2026-10-01', 'johto': '2026-10-02', 'hoenn': '2026-10-02', 'sinnoh': '2026-10-02', 'unova': '2026-10-02'}
front_source = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-v/black-white/{dex}.png'
official_rights = 'Nintendo / Game Freak / The Pokémon Company'


def resolve_action(animations, state):
    animation = next(a for a in animations if a.findtext('Name') == state)
    while animation.findtext('CopyOf'):
        animation = next(a for a in animations if a.findtext('Name') == animation.findtext('CopyOf'))
    return animation


# Some upstream folders hold AnimData.xml without an Idle or Walk sheet; those species are shown still.
def has_sheets(folder):
    if not (folder / 'AnimData.xml').exists():
        return False
    animations = ET.parse(folder / 'AnimData.xml').getroot().find('Anims')
    names = {a.findtext('Name') for a in animations}
    if not {'Idle', 'Walk'} <= names:
        return False
    return all((folder / f"{resolve_action(animations, state).findtext('Name')}-Anim.png").exists() for state in ['Idle', 'Walk'])


def read_sheet(folder, animation):
    source_state = animation.findtext('Name')
    width, height = int(animation.findtext('FrameWidth')), int(animation.findtext('FrameHeight'))
    durations = [int(d.text) for d in animation.find('Durations')]
    raw = (folder / f'{source_state}-Anim.png').read_bytes()
    sheet_width, sheet_height = struct.unpack('>II', raw[16:24])
    assert sheet_width == width * len(durations), (folder, source_state)
    assert sheet_height == height * 8, (folder, source_state)
    assert all(duration > 0 for duration in durations), (folder, source_state)
    return {'state': source_state, 'width': width, 'height': height, 'durations': durations}


# The client copy names the source sheet only when an action reuses another one (CopyOf), which keeps the bundle small.
def client_sheet(action, sheet):
    if sheet['state'] == action.capitalize():
        return {key: value for key, value in sheet.items() if key != 'state'}
    return sheet


# Attribution covers the imported actions only, not unrelated community-authored attacks.
def action_authors(folder, source_state):
    credits = (folder / 'credits.txt').read_text().splitlines()
    authors = [line.split('\t')[1] for line in credits if source_state in line.split('\t')[-1].split(',')]
    assert authors, (folder, source_state, 'missing action credit')
    return authors


def animated_species(entry, folder):
    animations = ET.parse(folder / 'AnimData.xml').getroot().find('Anims')
    sheets = {action: read_sheet(folder, resolve_action(animations, state)) for action, state in [('idle', 'Idle'), ('walk', 'Walk')]}
    authors = sorted({author for sheet in sheets.values() for author in action_authors(folder, sheet['state'])})
    credit = {
        'dex': entry['dex'], 'animation': 'pmd', 'source': f'https://github.com/PMDCollab/SpriteCollab/tree/master/sprite/{entry["dex"]:04d}',
        'credit': ', '.join(credit_names.get(author, author) for author in authors), 'authors': authors,
        'creditsPath': f'/assets/sprites/pokemon/{entry["species"]}/credits.txt', 'retrieved': retrieved[entry['region']],
    }
    return sheets, credit


def still_species(entry):
    credit = {
        'dex': entry['dex'], 'animation': 'still', 'source': front_source.format(dex=entry['dex']),
        'credit': official_rights, 'authors': [], 'creditsPath': None, 'retrieved': retrieved[entry['region']],
    }
    return None, credit


sprites, credits = {}, {}
for entry in catalog:
    folder = root / 'public/assets/sprites/pokemon' / entry['species']
    sprites[entry['species']], credits[entry['species']] = animated_species(entry, folder) if has_sheets(folder) else still_species(entry)
    assert (root / f'public/assets/sprites/pokemon/front/{entry["dex"]}.png').exists(), entry['species']

def client_sheets(sheet_set):
    return None if sheet_set is None else {action: client_sheet(action, sheet) for action, sheet in sheet_set.items()}


sprite_lines = ',\n'.join(f'  {json.dumps(species)}: {json.dumps(client_sheets(sheet_set), separators=(",", ":"))}' for species, sheet_set in sprites.items())
(root / 'src/assets/pokemon.ts').write_text(
    '// Generated by scripts/build-sprite-metadata.py from local source metadata. null: no animated sheets upstream, the front artwork is shown still.\n'
    '// Sheet files live at /assets/sprites/pokemon/<species>/<state>-Anim.png (state defaults to Idle or Walk); one row per direction (8), one column per frame.\n'
    'export const pokemonSprites = {\n' + sprite_lines + '\n} as const;\n\nexport type PokemonSpecies = keyof typeof pokemonSprites;\n'
)

credit_lines = ',\n'.join(f'  {json.dumps(species)}: {json.dumps(credit, ensure_ascii=False, separators=(",", ":"))}' for species, credit in credits.items())
(root / 'src/assets/pokemon-credits.ts').write_text(
    "// Generated by scripts/build-sprite-metadata.py: where each species' artwork comes from and who made it (see public/assets/README.md).\n// Read by server components only (the credits page), so this list never reaches the browser bundle.\n"
    'export const pokemonCredits = {\n' + credit_lines + '\n} as const;\n'
)

entries = [{key: entry[key] for key in ['dex', 'species', 'evolvesFrom', 'rarity']} for entry in catalog]
region_ranges = [{'id': region, 'firstDex': min(e['dex'] for e in catalog if e['region'] == region), 'lastDex': max(e['dex'] for e in catalog if e['region'] == region)} for region in regions]
(root / 'src/assets/pokedex.ts').write_text(
    '// Generated by scripts/build-sprite-metadata.py from scripts/data/<region>.json (PokeAPI species CSV); localized names are in messages.\n'
    'export const pokedex = [\n' + ',\n'.join('  ' + json.dumps(entry, separators=(', ', ': ')) for entry in entries) + '\n] as const;\n'
    'export type PokedexEntry = (typeof pokedex)[number];\nexport type PokedexDex = PokedexEntry["dex"];\n\n'
    '// Each region holds a contiguous range of Pokédex numbers.\n'
    'export const pokedexRegions = ' + json.dumps(region_ranges, indent=2) + ' as const;\nexport type PokedexRegion = (typeof pokedexRegions)[number]["id"];\n'
)

for locale in ['en', 'fr']:
    path = root / f'messages/{locale}.json'
    messages = json.loads(path.read_text())
    for entry in catalog:
        messages['Pokemon'][entry['species']] = entry['names'][locale]
        messages['Trainer']['species'][str(entry['dex'])] = entry['names'][locale]
    path.write_text(json.dumps(messages, indent=2, ensure_ascii=False) + '\n')
print(f'{len(catalog)} species, {sum(1 for s in sprites.values() if s is None)} still.')
