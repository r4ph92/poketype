import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { inflateSync } from 'node:zlib';
import { pokedex } from '../src/assets/pokedex';

// Regenerates src/assets/racer-portraits.ts: the visible bounds of each 96×96 front sprite (indexed PNG with a tRNS chunk), for the podium crop.
type Bounds = { x: number; y: number; width: number; height: number };

type IndexedImage = { width: number; height: number; bitDepth: number; transparency: Uint8Array; pixels: Buffer };

function readChunks(file: Buffer): Map<string, Buffer[]> {
  const chunks = new Map<string, Buffer[]>();
  for (let offset = 8; offset < file.length; ) {
    const length = file.readUInt32BE(offset);
    const type = file.toString('ascii', offset + 4, offset + 8);
    chunks.set(type, [...(chunks.get(type) ?? []), file.subarray(offset + 8, offset + 8 + length)]);
    offset += length + 12;
  }
  return chunks;
}

function readIndexedImage(path: string): IndexedImage {
  const chunks = readChunks(readFileSync(path));
  const header = chunks.get('IHDR')![0]!;
  if (header[9] !== 3 || header[12] !== 0) throw new Error(`${path} is not a non-interlaced indexed PNG`);
  const width = header.readUInt32BE(0);
  const bitDepth = header[8]!;
  const transparency = new Uint8Array(chunks.get('tRNS')?.[0] ?? []);
  const pixels = unfilter(inflateSync(Buffer.concat(chunks.get('IDAT')!)), Math.ceil((width * bitDepth) / 8));
  return { width, height: header.readUInt32BE(4), bitDepth, transparency, pixels };
}

// Indexed images filter byte by byte (one byte per pixel unit), each row prefixed with its filter type.
function unfilter(data: Buffer, rowBytes: number): Buffer {
  const rows = data.length / (rowBytes + 1);
  const output = Buffer.alloc(rows * rowBytes);
  for (let row = 0; row < rows; row++) {
    const filter = data[row * (rowBytes + 1)]!;
    for (let column = 0; column < rowBytes; column++) {
      const raw = data[row * (rowBytes + 1) + 1 + column]!;
      const left = column > 0 ? output[row * rowBytes + column - 1]! : 0;
      const up = row > 0 ? output[(row - 1) * rowBytes + column]! : 0;
      const upLeft = row > 0 && column > 0 ? output[(row - 1) * rowBytes + column - 1]! : 0;
      output[row * rowBytes + column] = (raw + predictor(filter, left, up, upLeft)) & 0xff;
    }
  }
  return output;
}

function predictor(filter: number, left: number, up: number, upLeft: number): number {
  if (filter === 1) return left;
  if (filter === 2) return up;
  if (filter === 3) return Math.floor((left + up) / 2);
  if (filter === 4) return paeth(left, up, upLeft);
  return 0;
}

function paeth(left: number, up: number, upLeft: number): number {
  const estimate = left + up - upLeft;
  const [toLeft, toUp, toUpLeft] = [Math.abs(estimate - left), Math.abs(estimate - up), Math.abs(estimate - upLeft)];
  if (toLeft <= toUp && toLeft <= toUpLeft) return left;
  return toUp <= toUpLeft ? up : upLeft;
}

function isVisible(image: IndexedImage, x: number, y: number): boolean {
  const rowBytes = Math.ceil((image.width * image.bitDepth) / 8);
  const bitOffset = x * image.bitDepth;
  const byte = image.pixels[y * rowBytes + (bitOffset >> 3)]!;
  const index = (byte >> (8 - image.bitDepth - (bitOffset & 7))) & ((1 << image.bitDepth) - 1);
  return (image.transparency[index] ?? 255) > 0;
}

function visibleBounds(image: IndexedImage): Bounds {
  const points = Array.from({ length: image.width * image.height }, (_, index) => ({ x: index % image.width, y: Math.floor(index / image.width) }));
  const visible = points.filter(({ x, y }) => isVisible(image, x, y));
  const [xs, ys] = [visible.map((point) => point.x), visible.map((point) => point.y)];
  const [left, top] = [Math.min(...xs), Math.min(...ys)];
  return { x: left, y: top, width: Math.max(...xs) - left + 1, height: Math.max(...ys) - top + 1 };
}

const portraits = Object.fromEntries(
  pokedex.map(({ dex, species }) => [species, { dex, ...visibleBounds(readIndexedImage(join('public/assets/sprites/pokemon/front', `${dex}.png`))) }]),
);
const source = `// Visible bounds of the existing front PNGs; used to place Pokémon feet on the podium. Generated by scripts/build-racer-portraits.ts.
import type { PokemonSpecies } from './pokemon';

export const racerPortraits: Record<PokemonSpecies, { dex: number; x: number; y: number; width: number; height: number }> = ${JSON.stringify(portraits, null, 2)};
`;
writeFileSync('src/assets/racer-portraits.ts', source);
