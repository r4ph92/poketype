"""Import the Kanto evolutions that happen by level in the original games, from PokeAPI evolution data.
Stone, trade and friendship evolutions are left out. Regenerate with: python3 scripts/import-level-evolutions.py
"""
from pathlib import Path
from urllib.request import urlopen
import csv
import io
import json

source = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_evolution.csv'
level_up_trigger = '1'
original_version_group = '1'

root = Path(__file__).resolve().parent.parent
catalog = json.loads((root / 'scripts/data/kanto.json').read_text())
evolves_from = {entry['dex']: entry['evolvesFrom'] for entry in catalog}

with urlopen(source, timeout=30) as response:
    rows = list(csv.DictReader(io.StringIO(response.read().decode('utf-8'))))

# Version group 1 (Red/Blue) holds the original rule; later version groups add regional alternatives.
evolutions = sorted(
    (
        {'from': evolves_from[into], 'into': into, 'level': int(row['minimum_level'])}
        for row in rows
        if (into := int(row['evolved_species_id'])) in evolves_from
        and evolves_from[into] is not None
        and row['version_group_id'] == original_version_group
        and row['evolution_trigger_id'] == level_up_trigger
        and row['minimum_level'] != ''
    ),
    key=lambda evolution: evolution['into'],
)
assert len({evolution['from'] for evolution in evolutions}) == len(evolutions), 'a species evolves by level into two forms'

header = f'// Generated by scripts/import-level-evolutions.py from {source} (original-game rules only).\n// Stone, trade and friendship evolutions are left out.\n'
(root / 'src/assets/level-evolutions.ts').write_text(
    header + 'export const levelEvolutions = ' + json.dumps(evolutions, indent=2) + ' as const;\n\nexport type LevelEvolution = (typeof levelEvolutions)[number];\n'
)
print(f'{len(evolutions)} level evolutions written.')
