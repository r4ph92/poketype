"""Import the evolutions that happen by leveling up for Pokédex #1-649, from PokeAPI evolution data (Generations I-V).
trigger is level (the original minimum level), friendship, move or location; the last three happen at the level set in gameConfig.evolution.
Babies, item, trade and shed evolutions are left out. Regenerate with: python3 scripts/import-level-evolutions.py
"""
import json
from catalog import root
from evolution_source import csv_source, evolution_rules

level_triggers = {'level', 'friendship', 'move', 'location'}


def evolution_of(pair, rule):
    evolution = {'from': pair[0], 'into': pair[1], 'trigger': rule[0]}
    return {**evolution, 'level': rule[1]} if rule[0] == 'level' else evolution


evolutions = sorted((evolution_of(pair, rule) for pair, rule in evolution_rules().items() if rule[0] in level_triggers), key=lambda evolution: evolution['into'])

lines = ',\n'.join('  ' + json.dumps(evolution, separators=(', ', ': ')) for evolution in evolutions)
header = f'// Generated by scripts/import-level-evolutions.py from {csv_source}pokemon_evolution.csv (Generations I-V).\n// Several evolutions from one form at the same level (Wurmple, Burmy, Eevee) are drawn at random by the server.\n'
(root / 'src/assets/level-evolutions.ts').write_text(
    header + 'export const levelEvolutions = [\n' + lines + '\n] as const;\n\nexport type LevelEvolution = (typeof levelEvolutions)[number];\n'
)
print(f'{len(evolutions)} level evolutions written.')
